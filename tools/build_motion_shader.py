#!/usr/bin/env python3
"""Generate the bounded native motion uniform ABI and shared evaluator."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
folder=ROOT/'Assets/MorphForgeAvatar/Shaders'
names=[]
for g in range(1,4):
 names += [f'_MF_M{g}_{s}'for s in ['Bank','Enabled','Base','Loop','Elapsed']]
 for b in range(2):
  names += [f'_MF_M{g}B{b}_{s}'for s in ['Count','Interp','PivotX','PivotY','PivotZ']]
  for k in range(4):names += [f'_MF_M{g}B{b}_K{k}{s}'for s in ['T','PX','PY','PZ','QX','QY','QZ','QW','S']]
props='\n'.join(f'        [HideInInspector] {n}("{n}",Float)=0'for n in names)
for filename in ['ParticleBoxCatalogMetadataGrid.shader','PixelText16.shader']:
 p=folder/filename;s=p.read_text();start='        // BEGIN GENERATED MOTION PROPERTIES';end='        // END GENERATED MOTION PROPERTIES'
 block=start+'\n'+props+'\n'+end
 if start in s:s=s[:s.index(start)]+block+s[s.index(end)+len(end):]
 else:s=s.replace('    Properties {','    Properties {\n'+block,1)if '    Properties {'in s else s.replace('    Properties\n    {','    Properties\n    {\n'+block,1)
 assert start in s,filename
 p.write_text(s)
lines=['// Generated by tools/build_motion_shader.py. Shared byte-cache motion ABI.','#ifndef MORPHFORGE_MOTION_INCLUDED','#define MORPHFORGE_MOTION_INCLUDED']
lines += ['float '+','.join(names[i:i+8])+';'for i in range(0,len(names),8)]
lines += ['''struct MFMotionPose {float3 pivot;float3 translation;float4 rotation;float scale;};
MFMotionPose MFIdentityPose(){MFMotionPose p;p.pivot=0;p.translation=0;p.rotation=float4(0,0,0,1);p.scale=1;return p;}
float4 MFUnitQuaternion(float4 q){float n=dot(q,q);return n>1e-10?q*rsqrt(n):float4(0,0,0,1);}
float4 MFSlerp(float4 a,float4 b,float t){a=MFUnitQuaternion(a);b=MFUnitQuaternion(b);float d=dot(a,b);if(d<0){b=-b;d=-d;}if(d>.9995)return MFUnitQuaternion(lerp(a,b,t));float angle=acos(clamp(d,0,1));return (sin((1-t)*angle)*a+sin(t*angle)*b)/max(sin(angle),1e-6);}
float3 MFRotateVector(float3 p,float4 q){return p+2*q.w*cross(q.xyz,p)+2*cross(q.xyz,cross(q.xyz,p));}
float3 MFApplyPose(float3 p,MFMotionPose m){return m.pivot+m.translation+MFRotateVector((p-m.pivot)*m.scale,m.rotation);}
''']
for g in range(1,4):
 for b in range(2):
  prefix=f'_MF_M{g}B{b}_';v=lambda k,s:prefix+f'K{k}'+s
  f3=lambda k,s:'float3('+','.join(v(k,s+a)for a in 'XYZ')+')'
  f4=lambda k:'float4('+','.join(v(k,'Q'+a)for a in 'XYZW')+')'
  lines += [f'MFMotionPose MFRead{g}{b}(float phase,float cell){{',f'if({prefix}Count<.5)return MFIdentityPose();',f'float times[4]={{{",".join(v(k,"T")for k in range(4))}}};',f'float3 positions[4]={{{",".join(f3(k,"P")for k in range(4))}}};',f'float4 rotations[4]={{{",".join(f4(k)for k in range(4))}}};',f'float scales[4]={{{",".join(v(k,"S")for k in range(4))}}};',f'int count=clamp((int)floor({prefix}Count+.5),1,4);int a=0;[unroll]for(int i=1;i<4;i++)if(i<count&&phase>=times[i])a=i;int z=min(a+1,count-1);',f'float t={prefix}Interp<.5?0:saturate((phase-times[a])/max(times[z]-times[a],1e-6));',f'MFMotionPose p;p.pivot=(float3({prefix}PivotX,{prefix}PivotY,{prefix}PivotZ)-float3(0,128,0))*cell;p.translation=lerp(positions[a],positions[z],t)*cell;p.rotation=MFSlerp(rotations[a],rotations[z],t);p.scale=max(lerp(scales[a],scales[z],t),1e-5);return p;','}']
lines += ['MFMotionPose MFGetMotion(float group,float cell){if(group<.5)return MFIdentityPose();']
for g in range(1,4):
 prefix=f'_MF_M{g}_';lines += [f'if(group<{g}+.5){{if({prefix}Enabled<.5)return MFIdentityPose();float phase={prefix}Base+{prefix}Elapsed;phase={prefix}Loop>.5?frac(phase):saturate(phase);if({prefix}Bank<.5)return MFRead{g}0(phase,cell);return MFRead{g}1(phase,cell);}}']
lines+=['return MFIdentityPose();}','#endif']
(folder/'MorphForgeMotion.cginc').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(names)} native motion floats')
